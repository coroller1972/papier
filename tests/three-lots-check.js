async (page) => {
  await page.emulateMedia({ media: null })
  await page.setViewportSize({ width: 1440, height: 1000 })
  const assert = (value, message) => { if (!value) throw new Error(message) }
  const editor = page.getByRole('textbox', { name: 'Contenu Markdown' })
  const setText = async text => { await editor.focus(); await editor.press('ControlOrMeta+a'); await page.keyboard.insertText(text); await page.locator('#print-document[aria-busy="true"]').waitFor({ state: 'attached' }) }
  const editorText = () => editor.evaluate(element => Array.from(element.querySelectorAll('.cm-line')).map(line => line.textContent).join('\n'))
  const ready = () => page.getByText('Aperçu à jour', { exact: true }).waitFor()
  const saved = () => page.getByText('Enregistré dans ce navigateur', { exact: true }).waitFor()
  await editor.waitFor()
  await setText('bonjour')
  await editor.press('ControlOrMeta+a')
  await editor.press('ControlOrMeta+b')
  assert(await editorText() === '**bonjour**', 'Bold shortcut failed')
  await editor.press('ControlOrMeta+z')
  assert(await editorText() === 'bonjour', 'Bold undo failed')
  await editor.press('ControlOrMeta+a')
  await editor.press('ControlOrMeta+i')
  assert(await editorText() === '*bonjour*', 'Italic shortcut failed')
  await setText('lien')
  await editor.press('ControlOrMeta+a')
  await editor.press('ControlOrMeta+k')
  assert(await editorText() === '[lien](https://)', 'Link shortcut failed')
  await setText('titre')
  await editor.press('ControlOrMeta+Shift+h')
  assert(await editorText() === '## titre', 'Heading shortcut failed')
  await setText('élément')
  await page.getByRole('button', { name: 'Liste', exact: true }).click()
  assert(await editorText() === '- élément', 'List button failed')
  await setText('citation')
  await page.getByRole('button', { name: 'Citation', exact: true }).click()
  assert(await editorText() === '> citation', 'Quote button failed')
  await setText('code')
  await editor.press('ControlOrMeta+a')
  await page.getByRole('button', { name: 'Code', exact: true }).click()
  assert(await editorText() === '`code`', 'Code button failed')
  await setText('alpha alpha ALPHA')
  await editor.press('ControlOrMeta+f')
  await page.getByRole('textbox', { name: 'Rechercher', exact: true }).fill('alpha')
  await page.getByRole('textbox', { name: 'Remplacer par', exact: true }).fill('bêta')
  await page.getByRole('button', { name: 'Tout remplacer', exact: true }).click()
  await page.getByRole('button', { name: 'Fermer la recherche', exact: true }).click()
  assert(await editorText() === 'bêta bêta bêta', 'Replace all failed')
  await editor.focus()
  await editor.press('ControlOrMeta+z')
  assert(await editorText() === 'alpha alpha ALPHA', 'Replace undo failed')
  await setText('# Titre\n\n**gras** et *italique*')
  assert(await editor.locator('.cm-line span[class]').count() > 2, 'Syntax highlighting absent')

  await page.locator('input[webkitdirectory]').setInputFiles('tests/fixtures/navigation')
  await page.getByRole('combobox', { name: 'Document Markdown à afficher' }).waitFor()
  await page.getByRole('button', { name: 'Parcourir les documents' }).click()
  const browser = page.getByRole('navigation', { name: 'Documents du dossier' })
  assert(await browser.locator('summary').count() === 2, 'Folder hierarchy missing')
  await page.getByRole('searchbox', { name: 'Rechercher un document' }).fill('GUIDES/guide edition')
  assert(await browser.locator('.document-entry').count() === 1, 'Path/accent search failed')
  await browser.getByRole('button', { name: 'guides/guide édition.markdown', exact: true }).click()
  const originalGuide = await editorText()
  await setText('# Guide modifié\n\n<!-- pagebreak -->\n\n## Seconde partie\n\n[Retour](../accueil.md)')
  await saved()
  await page.getByRole('button', { name: 'Parcourir les documents' }).click()
  await page.getByRole('navigation', { name: 'Documents du dossier' }).getByRole('button', { name: 'guides/guide édition.markdown — modifié depuis l’import', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  const changedGuide = await editorText()
  await setText(originalGuide)
  await page.getByRole('button', { name: 'Parcourir les documents' }).click()
  assert(await page.getByRole('button', { name: 'guides/guide édition.markdown', exact: true }).count() === 1, 'Modified badge did not clear on original content')
  await page.keyboard.press('Escape')
  await setText(changedGuide)
  await page.getByRole('combobox', { name: 'Document Markdown à afficher' }).selectOption('accueil.md')
  await ready()
  await page.locator('#print-document').getByRole('link', { name: 'Lire le guide' }).click()
  await ready()
  assert(await page.getByRole('combobox', { name: 'Document Markdown à afficher' }).inputValue() === 'guides/guide édition.markdown', 'Relative document link failed')
  assert((await editorText()).includes('Guide modifié'), 'Modified document not loaded through link')
  await page.waitForFunction(() => document.querySelector('.page-navigation select')?.value === '2')
  await page.locator('#print-document').getByRole('link', { name: 'Retour', exact: true }).click()
  await ready()
  await page.locator('#print-document').getByRole('link', { name: 'Lien absent' }).click()
  await page.locator('.navigation-error').waitFor()
  assert(await page.getByRole('combobox', { name: 'Document Markdown à afficher' }).inputValue() === 'accueil.md', 'Missing link changed the document')
  await page.locator('.navigation-error button').click()
  await page.locator('#print-document').getByRole('link', { name: 'Hors dossier' }).click()
  await page.locator('.navigation-error').waitFor()
  assert(await page.getByRole('combobox', { name: 'Document Markdown à afficher' }).inputValue() === 'accueil.md', 'Outside-folder link left the workspace')
  await page.locator('.navigation-error button').click()
  await saved()
  await page.reload()
  await editor.waitFor()
  await page.getByRole('button', { name: 'Parcourir les documents' }).click()
  await page.getByRole('button', { name: 'guides/guide édition.markdown — modifié depuis l’import', exact: true }).waitFor()
  await page.keyboard.press('Escape')

  const longText = '# Long\n\n' + Array.from({length: 70}, (_, i) => `## Chapitre ${i}\n\n` + 'Texte de contrôle. '.repeat(30)).join('\n\n')
  await setText(longText + '\n\n```mermaid\nflowchart LR\nA --> B\n```')
  await ready()
  const stats = await page.evaluate(async () => (await import(performance.getEntriesByType('resource').map(entry => entry.name).filter(url => new URL(url).pathname === '/src/lib/markdown.ts' && new URL(url).searchParams.has('t')).at(-1) || '/src/lib/markdown.ts')).getMermaidCacheStats())
  await page.getByRole('combobox', { name: 'Page à afficher' }).selectOption('4')
  await editor.focus()
  await editor.press('ControlOrMeta+End')
  await page.keyboard.insertText('\n\nAjout sans modifier le diagramme.')
  await page.locator('#print-document[aria-busy="true"]').waitFor({ state: 'attached' })
  await ready()
  assert(await page.getByRole('combobox', { name: 'Page à afficher' }).inputValue() === '4', 'Editing reset preview position')
  const after = await page.evaluate(async () => (await import(performance.getEntriesByType('resource').map(entry => entry.name).filter(url => new URL(url).pathname === '/src/lib/markdown.ts' && new URL(url).searchParams.has('t')).at(-1) || '/src/lib/markdown.ts')).getMermaidCacheStats())
  assert(after.renders === stats.renders && after.hits > stats.hits, 'Unchanged Mermaid rendered again')
  await setText('```mermaid\nflowchart LR\nA --> C\n```\n\n```mermaid\nflowchart LR\nA --> C\n```')
  await ready()
  assert(await page.locator('#print-document svg').count() === 2, 'Diagram duplicated by pagination')
  const ids = await page.locator('#print-document svg [id], #print-document svg[id]').evaluateAll(nodes => nodes.map(node => node.id))
  assert(new Set(ids).size === ids.length, 'Cached diagrams reuse SVG ids')
  const updated = await page.evaluate(async () => (await import(performance.getEntriesByType('resource').map(entry => entry.name).filter(url => new URL(url).pathname === '/src/lib/markdown.ts' && new URL(url).searchParams.has('t')).at(-1) || '/src/lib/markdown.ts')).getMermaidCacheStats())
  assert(updated.renders === stats.renders + 1, 'Changed diagram was not rendered exactly once: ' + JSON.stringify({stats,updated}))

  const beforeCancel = await page.evaluate(async () => (await import(performance.getEntriesByType('resource').map(entry => entry.name).filter(url => new URL(url).pathname === '/src/lib/pagination.ts' && new URL(url).searchParams.has('t')).at(-1) || '/src/lib/pagination.ts')).getPaginationStats())
  await setText(longText.repeat(8))
  await page.waitForFunction(() => document.querySelectorAll('.pagination-staging .pagedjs_page').length >= 3)
  await setText('# Version finale\n\nTexte court.')
  await ready()
  const afterCancel = await page.evaluate(async () => (await import(performance.getEntriesByType('resource').map(entry => entry.name).filter(url => new URL(url).pathname === '/src/lib/pagination.ts' && new URL(url).searchParams.has('t')).at(-1) || '/src/lib/pagination.ts')).getPaginationStats())
  assert(afterCancel.cancelled > beforeCancel.cancelled, 'Obsolete pagination not cancelled')
  assert(afterCancel.pages - beforeCancel.pages < 70, 'Obsolete pagination ran to completion')
  assert(await page.locator('#print-document .pagedjs_page').count() === 1, 'Obsolete pages committed')
  assert((await page.locator('#print-document').textContent()).includes('Version finale'), 'Latest content lost')

  await saved()
  await page.evaluate(() => {
    window.storageWrites = []
    window.originalPut = IDBObjectStore.prototype.put
    IDBObjectStore.prototype.put = function (...args) { window.storageWrites.push(this.name); return window.originalPut.apply(this, args) }
  })
  await editor.focus()
  await editor.press('ControlOrMeta+End')
  await page.keyboard.type(' Modification rapide de contrôle.', { delay: 5 })
  await saved()
  const writes = await page.evaluate(() => window.storageWrites)
  await page.evaluate(() => { IDBObjectStore.prototype.put = window.originalPut })
  assert(writes.filter(name => name === 'session').length <= 3, 'Saves were not coalesced')
  assert(!writes.includes('assets'), 'Images rewritten while typing')
  assert(writes.filter(name => name === 'documents').length <= 3, 'Unchanged documents rewritten')
  await page.reload()
  await editor.waitFor()
  assert((await editorText()).includes('Modification rapide de contrôle.'), 'Latest save was not persisted')

  await ready()
  await saved()
  await page.screenshot({path:'output/playwright/three-lots-desktop.png'})
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button', {name:'Parcourir les documents'}).click()
  await page.screenshot({path:'output/playwright/three-lots-mobile.png'})
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile overflow')
  await page.evaluate(result => { window.threeLotsResults = result }, { cache: after, cancellation: afterCancel, writes })
}
